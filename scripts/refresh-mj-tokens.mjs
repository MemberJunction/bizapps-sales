#!/usr/bin/env node
/**
 * Rewrites `scripts/mj-tokens.json`, the list of `--mj-*` design tokens the token gate accepts.
 *
 * The tokens are defined in MemberJunction's `_tokens.scss`, which the Explorer host loads. No
 * package this repo installs ships that file, so the gate cannot read it from `node_modules`; the
 * names are copied here instead, from the MJ release this repo builds against.
 *
 * Run it when bumping MemberJunction (see "Bumping to a new 6.1.N" in CLAUDE.md):
 *
 *     node scripts/refresh-mj-tokens.mjs                  # fetches _tokens.scss at the v<version> tag
 *     node scripts/refresh-mj-tokens.mjs <path/_tokens.scss>   # reads a local copy instead
 *
 * The version is the exact `@memberjunction/core` devDependency anchor in `packages/Angular`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const OUT = join(ROOT, 'scripts/mj-tokens.json');
const TOKENS_PATH = 'packages/Angular/Generic/shared/src/lib/_tokens.scss';

function readMjVersion() {
    const pkg = JSON.parse(readFileSync(join(ROOT, 'packages/Angular/package.json'), 'utf8'));
    const version = pkg.devDependencies?.['@memberjunction/core'];
    if (!version || !/^\d+\.\d+\.\d+$/.test(version)) {
        throw new Error(`packages/Angular devDependencies has no exact @memberjunction/core anchor (found "${version}")`);
    }
    return version;
}

async function readTokensSource(version, localPath) {
    if (localPath) return readFileSync(localPath, 'utf8');
    const url = `https://raw.githubusercontent.com/MemberJunction/MJ/v${version}/${TOKENS_PATH}`;
    const response = await fetch(url);
    if (!response.ok) throw new Error(`GET ${url} returned ${response.status}`);
    return response.text();
}

function extractTokenNames(source) {
    const names = new Set();
    for (const match of source.matchAll(/^\s*(--mj-[a-z0-9-]+)\s*:/gm)) names.add(match[1]);
    return [...names].sort();
}

const version = readMjVersion();
const tokens = extractTokenNames(await readTokensSource(version, process.argv[2]));
if (tokens.length === 0) {
    console.error('refresh-mj-tokens: ERROR — no --mj-* definitions found; refusing to write an empty list.');
    process.exit(2);
}
const body = {
    _comment: `Generated by scripts/refresh-mj-tokens.mjs from MemberJunction's ${TOKENS_PATH}. Do not edit by hand.`,
    mjVersion: version,
    tokens,
};
writeFileSync(OUT, JSON.stringify(body, null, 2) + '\n');
console.log(`refresh-mj-tokens: wrote ${tokens.length} token(s) from MJ v${version} to scripts/mj-tokens.json.`);
