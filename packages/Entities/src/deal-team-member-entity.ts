/**
 * @fileoverview The shared `DealTeamMember` entity subclass — the employee-or-person rule, on the entity
 * so the browser and the server run the same code.
 *
 * A team member is EITHER an MJ Employee (the internal rep, the common case) OR a common.Person (a
 * partner rep or contractor). The table enforces it with `CK_DealTeamMember_EmployeeXorPerson`, and
 * until this class nothing above the database did. A row that ended up with both — a new employee
 * picked on a row whose Person was already filled — reached SQL and came back as a raw CHECK
 * constraint error, on the exact path the duplicate-role refusal tells a user to take ("change that
 * row's employee").
 *
 * Two halves, and both are needed:
 *
 *   - `Set()` CLEARS THE OTHER FIELD when one is given a value, so changing who holds the row is one
 *     action rather than two. It is on the entity rather than a form because the Internal team grid is
 *     MJ's generic related-entity grid with no hook to attach to, and the generated team row form is
 *     regenerated by CodeGen.
 *   - `Validate()` REFUSES both-or-neither with a message a user can act on, for every write that did
 *     not go through `Set()` — `SetMany`, a hydrated payload, an API caller. The CHECK constraint stays
 *     as the backstop it was written to be.
 *
 * `DealTeamMemberEntityServer` extends THIS class, so the server keeps both and adds the rules that need
 * a database on top.
 *
 * @module @mj-biz-apps/sales-entities
 */
import { BaseEntity, ValidationErrorInfo, ValidationErrorType, ValidationResult } from '@memberjunction/core';
import { RegisterClass } from '@memberjunction/global';

import { mjBizAppsSalesDealTeamMemberEntity } from './generated/entity_subclasses';

/** Each identity field and the one it excludes. */
const OTHER_IDENTITY_FIELD: Readonly<Record<string, string>> = {
    EmployeeID: 'PersonID',
    PersonID: 'EmployeeID',
};

/** Each identity field's display name, joined in by the view and read-only on the entity. */
const IDENTITY_NAME_FIELD: Readonly<Record<string, string>> = {
    EmployeeID: 'Employee',
    PersonID: 'Person',
};

export const TEAM_MEMBER_BOTH_MESSAGE =
    'A team member is either an employee or a person, not both. Clear one of them.';
export const TEAM_MEMBER_NEITHER_MESSAGE =
    'Choose an employee, or a person for someone outside the company.';

function hasValue(value: unknown): boolean {
    return value !== null && value !== undefined && value !== '';
}

@RegisterClass(BaseEntity, 'MJ_BizApps_Sales: Deal Team Members')
export class DealTeamMemberEntity extends mjBizAppsSalesDealTeamMemberEntity {
    /**
     * Giving EmployeeID or PersonID a value clears the other.
     *
     * Only a NON-EMPTY value clears, so emptying one field never empties its partner. Loads do not come
     * through here (`SetMany` writes with `SetLocal`), so reading a stored row changes nothing.
     *
     * The cleared field's display name goes with it (#437): the view's `Person` / `Employee` column
     * would otherwise keep showing the old holder until a reload, so the row looks as if both are set.
     */
    public override Set(FieldName: string, Value: unknown): void {
        super.Set(FieldName, Value);
        const other = OTHER_IDENTITY_FIELD[FieldName];
        if (other && hasValue(Value) && hasValue(this.Get(other))) {
            super.Set(other, null);
            this.clearDisplayName(IDENTITY_NAME_FIELD[other]);
        }
    }

    /**
     * Empties a view-joined name field. Such a field is read-only and accepts one write after a load,
     * so the one-write flag is re-armed first, the same way MJ re-arms it when it reloads a record.
     */
    private clearDisplayName(fieldName: string): void {
        const field = this.GetFieldByName(fieldName);
        if (!field) {
            return;
        }
        field.ResetNeverSetFlag();
        field.Value = null;
    }

    /**
     * @remarks `super.Validate()` carries the generated field checks, so its result is built upon rather
     * than replaced.
     */
    public override Validate(): ValidationResult {
        const result = super.Validate();
        const hasEmployee = hasValue(this.EmployeeID);
        const hasPerson = hasValue(this.PersonID);
        if (hasEmployee && hasPerson) {
            result.Success = false;
            result.Errors.push(
                new ValidationErrorInfo('PersonID', TEAM_MEMBER_BOTH_MESSAGE, this.PersonID, ValidationErrorType.Failure),
            );
        } else if (!hasEmployee && !hasPerson) {
            result.Success = false;
            result.Errors.push(
                new ValidationErrorInfo('EmployeeID', TEAM_MEMBER_NEITHER_MESSAGE, this.EmployeeID, ValidationErrorType.Failure),
            );
        }
        return result;
    }
}
